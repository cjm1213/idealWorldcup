//  - items : "이름|부제" 를 쉼표나 줄바꿈으로 구분. 부제는 생략 가능
//            특정 후보만 다른 파일을 쓰려면 parse() 대신 { name, sub, img: "경로" } 객체를 직접 넣어도 됩니다.

export function parse(src) {
  const seen = new Set();
  return src.split(/[,\n]/).map(s => s.trim()).filter(Boolean).map(s => {
    const [name, sub = ""] = s.split("|").map(x => x.trim());
    return { name, sub };
  }).filter(c => !seen.has(c.name) && seen.add(c.name));
}

